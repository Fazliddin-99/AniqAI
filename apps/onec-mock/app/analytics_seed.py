def receivables_movement(month: str, buyer_ref: str) -> tuple[float, float]:
    """(Дт=отгрузка с НДС, Кт=оплата) по покупателю за месяц.

    Оплаты: все платят с лагом ~в месяц 90% отгрузки прошлого месяца, кроме
    MEGA TRADE, который с июня платит только 60% — копит долг.
    """
    shipped = sum(r for _, b, _, r, _ in SALES.get(month, []) if b == buyer_ref) * VAT
    ms = months()
    idx = ms.index(month) if month in ms else -1
    prev_shipped = 0.0
    if idx > 0:
        prev = ms[idx - 1]
        prev_shipped = sum(r for _, b, _, r, _ in SALES.get(prev, []) if b == buyer_ref) * VAT
    share = 0.6 if (buyer_ref == "CP-101" and month >= "2026-06") else 0.9
    paid = round(prev_shipped * share, 2)
    return round(shipped, 2), paid
